import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as sass from 'sass';

const root = new URL('../', import.meta.url);
const vendor = new URL('node_modules/bulma/', root);
const { version } = JSON.parse(await readFile(new URL('package.json', vendor), 'utf8'));
const license = await readFile(new URL('LICENSE', vendor), 'utf8');
const documentStyles = await readFile(new URL('styles/doc.css', root), 'utf8');
const { css: bulmaStyles } = sass.compile(fileURLToPath(new URL('styles/bulma.scss', root)), {
  loadPaths: [fileURLToPath(new URL('node_modules/', root))],
  style: 'compressed',
  charset: false,
});

const banner = '/* Generated by npm run build:css from styles/doc.css and styles/bulma.scss. */';
const stylesheet = `${banner}\n/*! Bulma v${version}\n\n${license.trim()}\n*/\n@layer bulma {\n${bulmaStyles}\n}\n\n${documentStyles.trimEnd()}\n`;
await writeFile(new URL('assets/doc.css', root), stylesheet);
